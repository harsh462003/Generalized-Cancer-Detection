def blind_deconvolution(image):
    print("   1️⃣ Blind Deconvolution...")
    img_float = img_as_float(image)

    if len(image.shape) == 3:
        result = np.zeros_like(img_float)
        psf = np.ones((5, 5)) / 25
        for i in range(image.shape[2]):
            result[:, :, i], _ = restoration.unsupervised_wiener(img_float[:, :, i], psf)
    else:
        psf = np.ones((5, 5)) / 25
        result, _ = restoration.unsupervised_wiener(img_float, psf)

    return img_as_ubyte(np.clip(result, 0, 1))

def tv_deconvolution(image):
    print("   2️⃣ TV Deconvolution...")
    img_float = img_as_float(image)
    kernel = np.outer(signal.windows.gaussian(7, 2), signal.windows.gaussian(7, 2))
    kernel = kernel / kernel.sum()

    if len(image.shape) == 3:
        result = np.zeros_like(img_float)
        for i in range(image.shape[2]):
            denoised = denoise_tv_chambolle(img_float[:, :, i], weight=0.05)
            result[:, :, i] = restoration.richardson_lucy(denoised, kernel, num_iter=30, clip=False)
    else:
        denoised = denoise_tv_chambolle(img_float, weight=0.05)
        result = restoration.richardson_lucy(denoised, kernel, num_iter=30)

    return img_as_ubyte(np.clip(result, 0, 1))

def nlm_sharpen(image):
    print("   3️⃣ NLM + Sharpen...")
    img_float = img_as_float(image)

    if len(image.shape) == 3:
        result = np.zeros_like(img_float)
        for i in range(image.shape[2]):
            sigma_est = estimate_sigma(img_float[:, :, i], average_sigmas=True)
            denoised = denoise_nl_means(img_float[:, :, i], h=1.15 * sigma_est, fast_mode=True, patch_size=5, patch_distance=6)
            blurred = ndimage.gaussian_filter(denoised, sigma=1)
            result[:, :, i] = denoised + 2.5 * (denoised - blurred)
    else:
        sigma_est = estimate_sigma(img_float, average_sigmas=True)
        denoised = denoise_nl_means(img_float, h=1.15 * sigma_est, fast_mode=True, patch_size=5, patch_distance=6)
        blurred = ndimage.gaussian_filter(denoised, sigma=1)
        result = denoised + 2.5 * (denoised - blurred)

    return img_as_ubyte(np.clip(result, 0, 1))

def rl_optimized(image):
    print("   4️⃣ RL Optimized...")
    img_float = img_as_float(image)
    kernel = np.outer(signal.windows.gaussian(7, 2.0), signal.windows.gaussian(7, 2.0))
