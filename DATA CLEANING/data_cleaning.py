hash_algo = imagehash.phash
near_hamming_threshold = 4  # <=4 bits = near duplicate

# ==== EXTRACTION ====
records = []
hash_map = {}  # hash -> first path
duplicates = []

# New (scans both .jpg and .jpeg)
