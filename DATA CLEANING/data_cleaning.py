    # Ensure it actually FAILS (< MIN_SHARPNESS_VAR); if rounding made it >=, nudge target down
    if s_val >= MIN_SHARPNESS_VAR:
        blurred, s_val, sigma = blur_to_target_sharpness(
            orig, min(tgt, MIN_SHARPNESS_VAR - 1.0), tol=TOL, max_sigma=MAX_SIGMA
        )
    status = "FAIL" if s_val < MIN_SHARPNESS_VAR else "PASS?"

    # Save originals & blurred as PNG (convert RGB->BGR for cv2.imwrite)
