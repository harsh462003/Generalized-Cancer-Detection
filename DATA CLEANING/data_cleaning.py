steps = 900      # increase if you can; saves intermediates
save_every = 200

for step in range(1, steps+1):
    G_deblur.train(); G_blur.train(); D_patch.train()

    # Deblur current blurry
    S_hat = G_deblur(B_small)  # candidate sharp

    # Update EMA proxy (acts as slowly-updating sharp target for content/perceptual)
    with torch.no_grad():
        if sharp_ema is None:
            sharp_ema = S_hat.detach()
        else:
            sharp_ema = EMA_MOM*sharp_ema + (1-EMA_MOM)*S_hat.detach()

    # Synthesize blur using BlurNet (BGAN-like) with noise conditioning
    z = make_noise(*S_hat.shape[-2:], device=DEVICE)
    B_syn = G_blur(S_hat, z)

    # ---------------- D step (relativistic) ----------------
    opt_D.zero_grad(set_to_none=True)
    d_real = D_patch(B_small)   # logits for real blur
    d_fake = D_patch(B_syn.detach())
    loss_D, _ = relativistic_loss(d_real, d_fake)
    loss_D.backward()
    opt_D.step()

    # ---------------- G step: Deblur + Blur with relativistic generator objective ----------------
    opt_G.zero_grad(set_to_none=True)
