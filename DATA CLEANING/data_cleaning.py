# ----------------------- Small Building Blocks -----------------------
class ConvBlock(nn.Module):
    def __init__(self, cin, cout, ks=3, s=1, p=1, act=True):
        super().__init__()
        self.conv = nn.Conv2d(cin, cout, ks, s, p)
        self.bn   = nn.BatchNorm2d(cout)
        self.act  = nn.ReLU(inplace=True) if act else nn.Identity()
    def forward(self, x):
        return self.act(self.bn(self.conv(x)))

class ResBlock(nn.Module):
    def __init__(self, c):
        super().__init__()
        self.c1 = ConvBlock(c,c)
        self.c2 = ConvBlock(c,c,act=False)
        self.act= nn.ReLU(inplace=True)
    def forward(self, x):
        return self.act(self.c2(self.c1(x)) + x)

class Down(nn.Module):
    def __init__(self, cin, cout):
        super().__init__()
        self.m = nn.Sequential(
            ConvBlock(cin, cout, 3,2,1),
            ResBlock(cout),
            ResBlock(cout)
        )
    def forward(self,x): return self.m(x)

"""
Patch: Fix Up block to accept explicit skip-channel size (skipc)
and wire DeblurNet with (cin, skipc, cout) that match encoder outputs.
"""

class Up(nn.Module):
    """
    Corrected Up block:
    - cin:   channels of the upsampled input (from deeper layer)
    - skipc: channels of the skip-connection tensor
    - cout:  desired output channels AFTER fusion
    """
    def __init__(self, cin, skipc, cout):
        super().__init__()
        # first bring 'cin' -> 'cout' with a 2x up-conv
        self.up = nn.ConvTranspose2d(cin, cout, 2, 2)
        # after concat, channels = cout + skipc
        fused = cout + skipc
        self.r1 = ResBlock(fused)
        self.r2 = ResBlock(fused)
        self.f  = ConvBlock(fused, cout)

    def forward(self, x, skip):
        x = self.up(x)                               # [B, cout, H2, W2]
        if x.shape[-2:] != skip.shape[-2:]:
            x = F.interpolate(x, size=skip.shape[-2:], mode="bilinear", align_corners=False)
        x = torch.cat([x, skip], dim=1)              # [B, cout+skipc, H, W]
        x = self.r2(self.r1(x))
        return self.f(x)                             # [B, cout, H, W]

class DeblurNet(nn.Module):
    """
    Corrected DeblurNet wiring:
    Encoder channel plan (base=48):
      s0: 48
      s1: 96
      s2: 192
      s3: 192   (we keep it compact by not doubling again)
    Decoder:
      u2 takes cin=192 (bottleneck), skipc=192 (s2), cout=96
      u1 takes cin=96,  skipc=48  (s0), cout=48
    """
    def __init__(self, base=48):
        super().__init__()
        self.inp = ConvBlock(3, base)         # s0: 48
        self.d1  = Down(base,   base*2)       # s1: 96
        self.d2  = Down(base*2, base*4)       # s2: 192
        self.d3  = Down(base*4, base*4)       # s3: 192
        self.b   = nn.Sequential(
            ResBlock(base*4), ResBlock(base*4), ResBlock(base*4)
        )
        # Decoder with explicit skip-channel sizes
        self.u2  = Up(cin=base*4, skipc=base*4, cout=base*2)  # 192 + 192 -> 96
        self.u1  = Up(cin=base*2, skipc=base,   cout=base)    # 96  + 48  -> 48
        self.out = nn.Conv2d(base, 3, 1)

    def forward(self, x):
        s0 = self.inp(x)         # 48
        s1 = self.d1(s0)         # 96
        s2 = self.d2(s1)         # 192
        s3 = self.d3(s2)         # 192
        b  = self.b(s3)          # 192
        x  = self.u2(b, s2)      # -> 96
        x  = self.u1(x, s0)      # -> 48
        return torch.sigmoid(self.out(x))


# ----------------------- BlurNet (BGAN_G-ish) -----------------------
class BlurNet(nn.Module):
    """
    Small CNN that takes candidate-sharp + noise and outputs a blurred version.
    Noise is a 4-channel spatial map (paper conditions with noise).
    """
    def __init__(self, base=32):
        super().__init__()
        self.head = ConvBlock(3+4, base)
        self.body = nn.Sequential(
            ResBlock(base), ResBlock(base), ResBlock(base),
            ConvBlock(base, base), ResBlock(base)
        )
        self.tail = nn.Conv2d(base, 3, 1)
    def forward(self, sharp, noise4):
        x = torch.cat([sharp, noise4], 1)
        x = self.body(self.head(x))
        return torch.sigmoid(self.tail(x))

# ----------------------- Patch Discriminator (Relativistic) -----------------------
class PatchDisc(nn.Module):
    def __init__(self, base=64):
        super().__init__()
        def block(cin, cout, ks=4, s=2, p=1, bn=True):
            layers=[nn.Conv2d(cin, cout, ks, s, p), nn.LeakyReLU(0.2, inplace=True)]
            if bn: layers.insert(1, nn.BatchNorm2d(cout))
            return nn.Sequential(*layers)
        self.net = nn.Sequential(
            block(3, base, bn=False),
            block(base, base*2),
            block(base*2, base*4),
            block(base*4, base*8, s=1),
            nn.Conv2d(base*8, 1, 4, 1, 1)  # 1xHxW map (logits)
        )
    def forward(self, x):  # logits
        return self.net(x)

# ----------------------- Perceptual Loss (VGG features before ReLU) -----------------------
class VGGPerceptual(nn.Module):
    def __init__(self, layers=(2,7,16,25)):  # conv1_2, conv2_2, conv3_3, conv4_3 (before their ReLU)
        super().__init__()
        vgg = models.vgg19(weights=models.VGG19_Weights.IMAGENET1K_V1).features.eval()
        self.slices = nn.ModuleList([
            nn.Sequential(*[vgg[j] for j in range(0, layers[0])]),
            nn.Sequential(*[vgg[j] for j in range(layers[0], layers[1])]),
            nn.Sequential(*[vgg[j] for j in range(layers[1], layers[2])]),
            nn.Sequential(*[vgg[j] for j in range(layers[2], layers[3])]),
        ])
        for p in self.parameters(): p.requires_grad_(False)
        self.register_buffer('mean', torch.tensor([0.485, 0.456, 0.406]).view(1,3,1,1))
        self.register_buffer('std',  torch.tensor([0.229, 0.224, 0.225]).view(1,3,1,1))
    def forward(self, x, y):
        # x,y in [0,1], normalize
        x = (x - self.mean)/self.std; y = (y - self.mean)/self.std
        loss=0.0
        for s in self.slices:
            x = s(x); y = s(y)
            loss += F.l1_loss(x, y)
        return loss

# ----------------------- Utilities -----------------------
def make_noise(h, w, batch=1, device=DEVICE):
    # 4-dim noise broadcast spatially (as in paper’s 4-d noise map idea)
    z = torch.randn(batch, 4, 1, 1, device=device)
    return z.expand(-1, -1, h, w)

def relativistic_loss(d_real, d_fake):
    """
    Relativistic average GAN objective (logistic):
    Encourage D(real) > D(fake) and D(fake) < D(real).
    """
    # logits shape: [B,1,H,W]
    # E[...] over batch&spatial
    mean_fake = torch.mean(d_fake)
    mean_real = torch.mean(d_real)
    loss_d = F.binary_cross_entropy_with_logits(d_real - mean_fake, torch.ones_like(d_real)) + \
             F.binary_cross_entropy_with_logits(d_fake - mean_real, torch.zeros_like(d_fake))
    # Generator counterpart (push/pull):
    loss_g = F.binary_cross_entropy_with_logits(d_fake - mean_real, torch.ones_like(d_fake)) + \
             F.binary_cross_entropy_with_logits(d_real - mean_fake, torch.zeros_like(d_real))
    return loss_d, loss_g

