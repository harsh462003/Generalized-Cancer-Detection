def super_aggressive_deblur(image):
    # STAGE 1: Richardson-Lucy with 100 iterations
    print("   Stage 1/5: Richardson-Lucy (100 iterations)...")
    img_float = img_as_float(image)

    kernel_size = 9
    sigma = 2.5
    kernel = np.outer(
        signal.windows.gaussian(kernel_size, sigma),
        signal.windows.gaussian(kernel_size, sigma)
    )
    kernel = kernel / kernel.sum()

    if len(image.shape) == 3:
        stage1 = np.zeros_like(img_float)
        for i in range(image.shape[2]):
            stage1[:, :, i] = restoration.richardson_lucy(
                img_float[:, :, i],
                kernel,
                num_iter=100,
                clip=False
            )
    else:
        stage1 = restoration.richardson_lucy(img_float, kernel, num_iter=100)

    # STAGE 2: Bilateral Filtering
    print("   Stage 2/5: Bilateral Filtering...")
    stage1_uint8 = img_as_ubyte(np.clip(stage1, 0, 1))

    if len(image.shape) == 3:
        stage2 = cv2.bilateralFilter(stage1_uint8, 15, 80, 80)
    else:
        stage2 = cv2.bilateralFilter(stage1_uint8, 15, 80, 80)

    # STAGE 3: Extreme Unsharp Masking
    print("   Stage 3/5: Extreme Unsharp Masking (4x)...")
    stage2_float = stage2.astype(float)

    if len(image.shape) == 3:
        stage3 = np.zeros_like(stage2_float)
        for i in range(image.shape[2]):
            blurred = ndimage.gaussian_filter(stage2_float[:, :, i], sigma=1.0)
            stage3[:, :, i] = stage2_float[:, :, i] + 4.0 * (stage2_float[:, :, i] - blurred)
    else:
        blurred = ndimage.gaussian_filter(stage2_float, sigma=1.0)
        stage3 = stage2_float + 4.0 * (stage2_float - blurred)

    # STAGE 4: High-Pass Enhancement
    print("   Stage 4/5: High-Pass Enhancement...")
    if len(image.shape) == 3:
        stage4 = np.zeros_like(stage3)
        for i in range(image.shape[2]):
            low_pass = ndimage.gaussian_filter(stage3[:, :, i], sigma=3)
            high_pass = stage3[:, :, i] - low_pass
            stage4[:, :, i] = stage3[:, :, i] + 2.0 * high_pass
    else:
        low_pass = ndimage.gaussian_filter(stage3, sigma=3)
        high_pass = stage3 - low_pass
        stage4 = stage3 + 2.0 * high_pass

    # STAGE 5: Edge Enhancement
    print("   Stage 5/5: Edge Enhancement...")
    stage4_uint8 = np.clip(stage4, 0, 255).astype(np.uint8)

    if len(image.shape) == 3:
        final = np.zeros_like(stage4_uint8)
        for i in range(image.shape[2]):
            edges = cv2.Canny(stage4_uint8[:, :, i], 50, 150)
            edges_float = edges.astype(float) / 255.0
            final[:, :, i] = np.clip(
                stage4_uint8[:, :, i].astype(float) + 30 * edges_float,
                0, 255
            ).astype(np.uint8)
    else:
        edges = cv2.Canny(stage4_uint8, 50, 150)
        edges_float = edges.astype(float) / 255.0
        final = np.clip(
            stage4_uint8.astype(float) + 30 * edges_float,
            0, 255
        ).astype(np.uint8)

    print("   ✅ All 5 stages complete!")
    return final

