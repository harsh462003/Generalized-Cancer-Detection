"""
Goal: Force the displayed image's grayscale mean (after RGB conversion) to a given target,
      e.g., brighter ≈ 249, darker ≈ 3, by adjusting only the Lab L* channel.
Why:  Directly setting Lab L*'s mean doesn't guarantee the RGB-gray mean due to nonlinearity,
      Lab↔RGB transforms, and gamut clipping. We solve it numerically on the final RGB domain.

Strategy:
1) Convert RGB→Lab; keep A,B fixed (color preserved).
2) Search for a bias 'beta' added to L (with clamping to [0,255]) that makes the final
   RGB->GRAY mean hit the target. If unreachable due to clipping/gamut, progressively
   reduce chroma (scale A,B toward neutral) to allow lower means (for very dark targets).
3) Repeat for a bright target and a dark target.

Notes:
- Only L is altered; A,B chroma are preserved unless desaturation is required to reach the target.
- Converges fast (bisection). Tolerance can be tightened if needed.
"""

import cv2
import numpy as np
import matplotlib.pyplot as plt

# ---------- paths ----------
path = "/content/TUM-QVHPHHNW.tif"

# ---------- helpers ----------
def to_rgb(img_bgr):
    return cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)

def rgb_to_lab(img_rgb):
    return cv2.cvtColor(img_rgb, cv2.COLOR_RGB2LAB)

def lab_to_rgb(lab):
    return cv2.cvtColor(lab, cv2.COLOR_LAB2RGB)

def gray_mean(img_rgb):
    # OpenCV's RGB2GRAY uses BT.601-like luma coefficients
    gray = cv2.cvtColor(img_rgb, cv2.COLOR_RGB2GRAY)
    return float(gray.mean())

def clamp_u8(x):
    return np.clip(x, 0, 255).astype(np.uint8)

def hit_gray_target_via_L_bias(L, A, B, target_gray, tol=0.5, max_iter=25, max_desat_steps=4):
    """
    Find L' = clamp(L + beta) s.t. mean(gray(L',A,B)) ≈ target_gray.
    If impossible (gamut/clipping), desaturate (A,B) progressively and retry.
    Returns: (L_adj, A_adj, B_adj, achieved_gray_mean, desat_factor)
    """
    A0, B0 = A.copy(), B.copy()
    # progressive desaturation factors (1.0 keeps chroma; lower = more neutral)
    factors = np.linspace(1.0, 0.6, max_desat_steps)

    for f in factors:
        A = clamp_u8((A0.astype(np.float32) - 128) * f + 128)
        B = clamp_u8((B0.astype(np.float32) - 128) * f + 128)

        # establish search bounds for beta (shift of L)
        # wide bounds; we clamp to [0,255] after adding beta
        lo, hi = -255.0, 255.0
        best = None

        for _ in range(max_iter):
            beta = 0.5*(lo + hi)
            Lp = clamp_u8(L.astype(np.float32) + beta)
            lab = cv2.merge((Lp, A, B))
            rgb = lab_to_rgb(lab)
            m = gray_mean(rgb)
            best = (Lp, A, B, m, f)

            if abs(m - target_gray) <= tol:
                return best  # good enough

